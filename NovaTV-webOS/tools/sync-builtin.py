#!/usr/bin/env python3
"""Regenerates js/data/builtin.js from the Android app's bundled playlist.

webOS 1.x adaptations:
  * logos point to files bundled in assets/logos/ (a 2014 TV cannot validate Wikimedia's
    Let's Encrypt certificate chain);
  * streams that TRT also serves over plain HTTP use http:// (older TLS stacks / root stores).
Usage: python3 tools/sync-builtin.py ../NovaTV/app/src/main/assets/playlists/turkiye_resmi.m3u
"""
import json
import re
import sys
import urllib.request

def plain_http_ok(url):
    """True if the same stream answers 200 over plain HTTP (no redirect to https)."""
    http_url = "http://" + url[len("https://"):]
    class NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *args, **kwargs):
            return None
    opener = urllib.request.build_opener(NoRedirect)
    try:
        with opener.open(urllib.request.Request(http_url, headers={"User-Agent": "NovaTV-build"}), timeout=10) as r:
            return r.status == 200
    except Exception:
        return False

def main(src):
    lines = []
    for line in open(src, encoding="utf-8").read().splitlines():
        if line.startswith("#EXTINF"):
            tid = re.search(r'tvg-id="([^"]+)"', line).group(1)
            local = "assets/logos/" + tid.rsplit(".", 1)[0].lower() + ".png"
            line = re.sub(r'tvg-logo="[^"]+"', 'tvg-logo="%s"' % local, line)
        elif line.startswith("https://") and plain_http_ok(line):
            line = "http://" + line[len("https://"):]
        lines.append(line)
    body = " +\n            ".join(json.dumps(l + "\n", ensure_ascii=False) for l in lines)
    print("/* GENERATED by tools/sync-builtin.py from the Android asset playlists/turkiye_resmi.m3u — do not edit.")
    print(" * Official, free public-broadcaster streams only (TRT, TBMM TV). Logos are bundled locally;")
    print(" * streams that are also served over plain HTTP use http:// for 2014-era TLS stacks. */")
    print("(function (NV) {")
    print("    'use strict';")
    print("    NV.BUILTIN = {")
    print("        id: 'builtin-tr',")
    print("        name: 'Türkiye – Resmi Ücretsiz Yayınlar',")
    print("        description: 'Uygulamayla gelir: TRT ve TBMM TV\\'nin kendi sunucularındaki resmi, ücretsiz canlı yayınları',")
    print("        text: " + body)
    print("    };")
    print("}(NV));")

if __name__ == "__main__":
    main(sys.argv[1])
